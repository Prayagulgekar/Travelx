import "server-only";
import { money } from "@/lib/domain/money";
import { CATEGORY_LABELS } from "@/lib/validation/quotations";
import { PAYMENT_METHOD_LABELS } from "@/lib/domain/payments";
import { statusLabel } from "@/lib/domain/status";
import type { Agency, Booking, Customer, ItineraryDay, Itinerary, Payment, Quotation, QuotationItem, Refund } from "@/types/models";
import { PdfWriter, pdfDate, pdfMoney } from "./layout";

function agencyLines(a: Agency): string[] {
  return [a.name, a.address ?? "", [a.city, a.country].filter(Boolean).join(", "), [a.phone, a.email].filter(Boolean).join("  |  "), a.tax_id ? `Tax ID: ${a.tax_id}` : ""];
}

function minutes(m: number | null): string {
  if (!m) return "";
  const h = Math.floor(m / 60);
  const r = m % 60;
  return h ? `${h}h${r ? ` ${r}m` : ""}` : `${r}m`;
}

export async function renderQuotationPdf(agency: Agency, q: Quotation, items: QuotationItem[]): Promise<Uint8Array> {
  const w = await PdfWriter.create(`${agency.name} - Quotation ${q.quotation_code}. Prices valid until ${pdfDate(q.valid_until)}. Generated by TravelX.`);
  w.header(`Quotation ${q.quotation_code}`, agencyLines(agency));
  const e = q.enquiry;
  const c = q.customer;
  w.text(q.title, { size: 14, bold: true });
  w.gap(6);
  w.keyValues([
    ["Quotation number", q.quotation_code],
    ["Status", statusLabel(q.status)],
    ["Issue date", pdfDate(q.issue_date)],
    ["Valid until", pdfDate(q.valid_until)],
  ], 4);
  w.sectionTitle("Customer");
  w.keyValues([
    ["Name", c?.full_name ?? "-"],
    ["Contact", [c?.phone, c?.email].filter(Boolean).join("  |  ")],
    ["Address", [c?.address, c?.city, c?.country].filter(Boolean).join(", ") || "-"],
    ["Customer ID", c?.customer_code ?? "-"],
  ]);
  if (e) {
    w.sectionTitle("Travel details");
    const travellers = [`${e.adults} adult(s)`, e.children ? `${e.children} child(ren)` : "", e.infants ? `${e.infants} infant(s)` : ""].filter(Boolean).join(", ");
    w.keyValues([
      ["From", e.source_location], ["Destination", e.destination],
      ["Travel dates", `${pdfDate(e.departure_date)} - ${pdfDate(e.return_date)}`], ["Travellers", `${travellers}; ${e.rooms} room(s)`],
    ]);
  }
  w.sectionTitle("Cost breakdown");
  w.table(
    [{ label: "Description", width: 38 }, { label: "Category", width: 18 }, { label: "Qty", width: 8, align: "right" },
     { label: "Unit price", width: 14, align: "right" }, { label: "Tax", width: 8, align: "right" }, { label: "Amount", width: 16, align: "right" }],
    items.map((i) => [i.description, CATEGORY_LABELS[i.category] ?? i.category, money(i.quantity).toString(),
      pdfMoney(i.unit_price, q.currency), `${money(i.tax_rate).toString()}%`, pdfMoney(i.line_total, q.currency)]),
  );
  w.gap(8);
  const discountLabel = q.discount_type === "percent" ? `Discount (${money(q.discount_value).toString()}%)` : "Discount";
  w.totals([
    { label: "Subtotal", value: pdfMoney(q.subtotal, q.currency) },
    { label: "Taxes", value: pdfMoney(q.tax_amount, q.currency) },
    ...(money(q.discount_amount).gt(0) ? [{ label: discountLabel, value: `- ${pdfMoney(q.discount_amount, q.currency)}` }] : []),
    { label: "Grand total", value: pdfMoney(q.grand_total, q.currency), strong: true },
  ]);
  if (q.payment_terms) { w.sectionTitle("Payment terms"); w.text(q.payment_terms, { size: 9 }); }
  if (q.terms) { w.sectionTitle("Terms and conditions"); w.text(q.terms, { size: 8.5, color: undefined }); }
  w.gap(10);
  w.text("Prices are subject to availability at the time of booking confirmation. This quotation is not a booking confirmation.", { size: 8, color: undefined });
  return w.finish();
}

export async function renderItineraryPdf(agency: Agency, it: Itinerary, days: ItineraryDay[], customerName?: string): Promise<Uint8Array> {
  const w = await PdfWriter.create(`${agency.name} - Itinerary "${it.name}". Generated by TravelX.`);
  w.header("Travel itinerary", agencyLines(agency));
  w.text(it.name, { size: 14, bold: true });
  w.gap(4);
  w.keyValues([
    ["Destination", it.destination], ["Travel dates", `${pdfDate(it.start_date)} - ${pdfDate(it.end_date)}`],
    ["Prepared for", customerName ?? "-"], ["Duration", `${days.length} day(s)`],
  ], 4);
  if (it.notes) { w.sectionTitle("Overview"); w.text(it.notes, { size: 9.5 }); }
  for (const d of days) {
    w.ensure(60);
    w.gap(8);
    w.text(`Day ${d.day_number}${d.day_date ? `  -  ${pdfDate(d.day_date)}` : ""}${d.title ? `  -  ${d.title}` : ""}`, { size: 11, bold: true });
    w.rule();
    if (d.notes) w.text(d.notes, { size: 9, lineGap: 1 });
    if (d.activities.length === 0) w.text("Free time / at leisure.", { size: 9 });
    for (const a of d.activities) {
      const meta = [a.start_time ? a.start_time.slice(0, 5) : "", a.location ?? "", minutes(a.duration_minutes)].filter(Boolean).join("  |  ");
      w.text(a.title, { size: 10, bold: true, x: w.left + 10 });
      if (meta) w.text(meta, { size: 8.5, x: w.left + 10 });
      if (a.description) w.text(a.description, { size: 9, x: w.left + 10 });
      if (a.notes) w.text(`Note: ${a.notes}`, { size: 8.5, x: w.left + 10 });
      w.gap(4);
    }
  }
  w.gap(10);
  w.text("Timings are indicative and may change due to local conditions. Supplier availability is confirmed separately at booking.", { size: 8 });
  return w.finish();
}

export async function renderReceiptPdf(agency: Agency, p: Payment, booking: Pick<Booking, "booking_code" | "destination" | "departure_date" | "return_date" | "total_amount" | "currency">,
  customer: Pick<Customer, "full_name" | "phone" | "email" | "customer_code">, refunds: Refund[], balance: { netCollected: string; outstanding: string }, recordedBy: string): Promise<Uint8Array> {
  const w = await PdfWriter.create(`${agency.name} - Payment receipt ${p.payment_code}. Generated by TravelX.`);
  w.header("Payment receipt", agencyLines(agency));
  w.text(`Receipt ${p.payment_code}`, { size: 14, bold: true });
  w.gap(4);
  w.keyValues([
    ["Receipt number", p.payment_code], ["Payment date", pdfDate(p.payment_date)],
    ["Status", statusLabel(p.status)], ["Method", PAYMENT_METHOD_LABELS[p.method]],
    ["Transaction reference", p.transaction_reference ?? "-"], ["Recorded by", recordedBy],
  ]);
  w.sectionTitle("Received from");
  w.keyValues([["Customer", customer.full_name], ["Contact", [customer.phone, customer.email].filter(Boolean).join("  |  ")]]);
  w.sectionTitle("Booking");
  w.keyValues([
    ["Booking", booking.booking_code], ["Destination", booking.destination],
    ["Travel dates", `${pdfDate(booking.departure_date)} - ${pdfDate(booking.return_date)}`], ["Booking value", pdfMoney(booking.total_amount, booking.currency)],
  ]);
  w.gap(8);
  w.totals([
    { label: "Amount of this payment", value: pdfMoney(p.amount, p.currency) },
    ...(money(p.refunded_amount).gt(0) ? [{ label: "Refunded from this payment", value: `- ${pdfMoney(p.refunded_amount, p.currency)}` }] : []),
    { label: "Total collected for booking", value: pdfMoney(balance.netCollected, p.currency) },
    { label: "Balance outstanding", value: pdfMoney(balance.outstanding, p.currency), strong: true },
  ]);
  if (refunds.length) {
    w.sectionTitle("Refunds");
    w.table([{ label: "Date", width: 20 }, { label: "Reason", width: 55 }, { label: "Amount", width: 25, align: "right" }],
      refunds.map((r) => [pdfDate(r.refund_date), r.reason, pdfMoney(r.amount, p.currency)]));
  }
  if (p.status === "pending") {
    w.gap(8);
    w.text("This payment is recorded as PENDING and has not yet been received. This document is not proof of payment.", { size: 9, bold: true });
  }
  return w.finish();
}
